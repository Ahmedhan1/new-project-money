DIALECTS = {"ar": {"EG", "Gulf"}}


# ------------------------------------------------------------------ helpers
def _local(uri: str | None) -> Path | None:
    if not uri:
        return None
    if uri.startswith("file://"):
        try:
            from nexus.contracts import local_path  # Account 2 helper (handles Windows drive letters) on the merged tree
            return local_path(uri)
        except Exception:  # noqa: BLE001
            from urllib.parse import urlparse
            from urllib.request import url2pathname
            return Path(url2pathname(urlparse(uri).path))
    if "://" in uri:
        return None
    return Path(uri)


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _validate_qr(qr: dict) -> list[str]:
    try:
        from nexus.contracts import media as a2  # Account 2's own validator (merged tree)
        return a2.validate(qr, "QualityReport")
    except Exception:  # noqa: BLE001 - Account 3 branch alone: the same required keys and types
        out = [f"QualityReport.{k} is required" for k in QR_REQUIRED if qr.get(k) is None]
        out += [f"QualityReport.{k} must be {t.__name__}" for k, t in QR_REQUIRED.items() if qr.get(k) is not None and not isinstance(qr[k], t)]
        if qr.get("schema") and not str(qr["schema"]).startswith("nexus.QualityReport/1"):
            out.append(f"QualityReport schema {qr['schema']!r} not supported")
        return out


def human_approved(value) -> bool:
    return isinstance(value, str) and value.strip().upper().startswith("APPROVED")


def findings(qr: dict) -> list[dict]:
    return [{"stage": s.get("stage") or s.get("name"), "check": c.get("check"), "severity": c.get("severity"), "detail": c.get("detail")}
            for s in (qr.get("stages") or []) if isinstance(s, dict) for c in (s.get("checks") or [])
            if isinstance(c, dict) and not c.get("ok")]


# ------------------------------------------------------------------ 1. quality
def quality(artifact: dict, qr: dict | None) -> dict:
    block, public, warn = [], [], []
    p = _local(artifact.get("uri"))
    if p is None:
        block.append(f"final output is not a local file ({artifact.get('uri')!r}); it cannot be verified before upload")
    elif not p.is_file():
        block.append(f"final output missing: {p}")
    elif artifact.get("sha256"):
        if sha256_file(p) != artifact["sha256"]:
            block.append("final output checksum does not match the artifact's sha256 (file changed after QA?)")
    else:
        warn.append("artifact has no sha256: integrity not checked")
    summary = None
    if qr is None:
        block.append("no QualityReport attached: a render that finished is not a render that passed QA")
    else:
        errs = _validate_qr(qr)
        if errs:
            block.append("QualityReport invalid: " + "; ".join(errs))
        else:
            out = str(qr["output"])
            names = {str(p), p.name, p.stem} if p else set()
            if qr.get("output_sha256") and artifact.get("sha256"):
                if qr["output_sha256"] != artifact["sha256"]:
                    block.append("QualityReport is for a different file (sha256 differs)")
            elif p and out not in names and Path(out).name not in names:
                block.append(f"QualityReport is for output {out!r}, not {p.name!r}")
            st = qr["status"]
            if st not in QR_STATUSES:
                block.append(f"QualityReport status {st!r} is not one Account 2 produces {sorted(QR_STATUSES)}")
            elif st != PASSED:
                block.append(f"QualityReport status is {st}")
            fs = findings(qr)
            crit = [f for f in fs if f["severity"] == "critical"]
            if crit:
                block.append(f"{len(crit)} critical quality finding(s): " + "; ".join(f"{f['check']}: {f['detail']}" for f in crit)[:400])
            if not human_approved(qr["human_approval"]):
                public.append(f"human review not completed (QualityReport.human_approval = {qr['human_approval'][:60]!r})")
            summary = {"status": st, "score": qr.get("score"), "human_approval": qr["human_approval"], "findings": fs,
                       "known_issues": qr.get("known_issues") or []}
    return {"upload_ok": not block, "public_ok": not block and not public, "blockers": block, "public_blockers": public,
            "warnings": warn, "report": summary}


# ------------------------------------------------------------------ 2. disclosure
def categories(media: list[dict] | None, audio: list[dict] | None, edits: list[str] | None) -> tuple[list[str], list[str]]:
    """-> (categories, problems). No provenance at all -> ['unknown']."""
    cats, probs = set(), []
    for g in media or []:
        c = g.get("classification")
        if c not in CLASSIFICATION:
            probs.append(f"unknown GeneratedMediaManifest.classification {c!r}")
            cats.add("unknown")
        elif CLASSIFICATION[c]:
            cats.add(CLASSIFICATION[c])
    for a in audio or []:
        k = a.get("kind")
        if k not in AUDIO:
            probs.append(f"unknown audio provenance {k!r}")
            cats.add("unknown")
        elif AUDIO[k]:
            cats.add(AUDIO[k])
    for e in edits or []:
        cats.add(EDITS.get(e, "unknown"))
    if media is None and audio is None and edits is None:
        cats.add("unknown")
    return sorted(cats), probs


def disclosure(platform: str, provenance: dict | None, decision: dict | None = None) -> dict:
    """provenance = {"media": [GeneratedMediaManifest...], "audio": [{"kind"}...], "edits": [...], "no_ai_attested_by": "owner"?}
    decision  = owner's record for platforms needing a human judgement: {"by", "contains_synthetic_media": bool, "reason"}."""
    fam = PLATFORM_FAMILY.get(platform, platform)
    cap = PLATFORMS[fam]
    prov = provenance or {}
    cats, probs = categories(prov.get("media"), prov.get("audio"), prov.get("edits"))
    ai = [c for c in cats if c != "unknown"]
    block, public = list(probs and [f"provenance: {'; '.join(probs)}"] or []), []
    attested = prov.get("no_ai_attested_by")
    if attested and ai:
        block.append(f"owner attested 'no AI' but provenance records AI use {ai}: refusing to label AI content as non-AI")
    no_ai = bool(attested) and not ai and not probs and attested == "owner"
    if no_ai:
        cats = []
    elif not cats:
        cats = ["unknown"]          # no AI recorded but nobody attested it: never silently non-AI
    flag = bool(cats)
    if decision is not None and fam == "youtube":
        if decision.get("by") not in ("owner",) or not isinstance(decision.get("contains_synthetic_media"), bool):
            block.append("disclosure decision must be {'by': 'owner', 'contains_synthetic_media': true|false, 'reason': ...}")
        elif decision["contains_synthetic_media"] is False and cats:
            if not str(decision.get("reason") or "").strip():
                block.append("owner decided 'not realistic synthetic media' without a reason; a reason is required")
            else:
                flag = False
        elif decision["contains_synthetic_media"] is True:
            flag = True
    needs_label = bool(cats)
    manual = fam == "snapchat"           # manual export: nothing is uploaded; the package tells the owner what to label
    if needs_label and manual:
        public.append(f"{platform}: manual upload - the owner must apply the AI label by hand ({cats})")
    elif needs_label and not cap["adapter_supports"]:
        public.append(f"{platform}: the content needs an AI disclosure ({cats}) but this adapter cannot set {cap['field'] or 'a label'}")
        if not cap["private_mode"]:
            block.append(f"{platform}: no private mode and no supported disclosure field - not uploaded")
    if "unknown" in cats and not (decision and fam == "youtube"):
        public.append("provenance unknown: the owner must record what is AI-generated before public publishing")
    if fam == "youtube" and needs_label and cap["human_decision_required"] and decision is None:
        public.append("YouTube asks whether the content is realistic altered/synthetic media: owner decision required for public")
    return {"platform": platform, "categories": cats, "field": cap["field"], "flag": flag, "adapter_supports": cap["adapter_supports"],
            "human_decision_required": cap["human_decision_required"], "decision": decision, "no_ai_attested": no_ai,
            "upload_ok": not block, "public_ok": not block and not public, "blockers": block, "public_blockers": public}


# ------------------------------------------------------------------ 3. language
def language_tag(lang: str | None, dialect: str | None = None) -> str | None:
    if not lang:
        return None
    if dialect:
        base = lang.split("-")[0]
        if dialect not in DIALECTS.get(base, set()):
            raise ValueError(f"unknown dialect {dialect!r} for {base!r} (known: {sorted(DIALECTS.get(base, set()))})")
        return f"{base}-{dialect}"
    return lang


def language(rec: dict | None, metadata_language: str | None = None, source_language: str = "en") -> dict:
    """rec = {"language", "dialect"?, "translation_qa": {"ok", ...}?, "terminology": {"ok", ...}?, "ocr_glyph": {"ok"}?,
    "voice": {"licence_ok": bool, "consent_problems": [...]}?, "review_items": [ids]?}"""
    block, public = [], []
    if rec is None:
        tag = metadata_language
        if tag and tag.split("-")[0] != source_language:
            public.append(f"output language {tag} has no language readiness record: draft only")
        return {"tag": tag, "state": "source_language" if not public else "draft_needs_native_review", "review_required": bool(public),
                "reviewer_approval": None, "upload_ok": True, "public_ok": not public, "blockers": block, "public_blockers": public}
    try:
        tag = language_tag(rec.get("language"), rec.get("dialect"))
    except ValueError as e:
        return {"tag": None, "state": "invalid", "review_required": True, "reviewer_approval": None, "upload_ok": False,
                "public_ok": False, "blockers": [str(e)], "public_blockers": []}
    if metadata_language and tag and metadata_language not in (tag, tag.split("-")[0]):
        block.append(f"metadata language {metadata_language!r} does not match the output's language {tag!r}")
    for k in ("translation_qa", "terminology", "ocr_glyph"):
        v = rec.get(k)
        if isinstance(v, dict) and v.get("ok") is False:
            public.append(f"{k} failed: {v.get('detail') or v}")
    voice = rec.get("voice")
    if voice:
        if voice.get("licence_ok") is not True:
            block.append("voice licence not cleared for commercial use")
        if voice.get("consent_problems"):
            block.append("voice consent: " + "; ".join(voice["consent_problems"]))
    from ..language import review, readiness
    st = review.stats().get(tag or "", {})
    base_ok = st.get("reviewed", 0) >= readiness.REVIEW_MIN_LINES and (st.get("acceptance") or 0) >= readiness.REVIEW_MIN_ACCEPT
    required = bool(tag) and tag.split("-")[0] != source_language and (tag in ALWAYS_REVIEW or not base_ok)
    approval = None
    if required:
        ids = rec.get("review_items") or []
        if not ids:
            approval = "not_submitted"
            public.append(f"{tag}: native review required and no lines were submitted for review")
        else:
            items = {i["id"]: i for i in review.queue(None, None)}
            missing = [i for i in ids if i not in items]
            wrong = sorted({items[i]["lang"] for i in ids if i in items and items[i]["lang"] != tag})
            states = [items[i]["status"] for i in ids if i in items]
            if missing:
                block.append(f"review items not found: {missing[:3]}")
            if wrong:
                public.append(f"review was for {wrong}, output is {tag}: varieties are not interchangeable")
            if any(s == "rejected" for s in states):
                approval = "rejected"
                public.append(f"{tag}: a native reviewer rejected {states.count('rejected')} line(s)")
            elif any(s == "pending" for s in states):
                approval = "pending"
                public.append(f"{tag}: native review pending for {states.count('pending')} line(s)")
            elif not missing and not wrong:
                approval = "approved"
            else:
                approval = "invalid"
    state = "ready" if not block and not public else "draft_needs_native_review" if required and approval != "approved" else "draft"
    return {"tag": tag, "state": state, "review_required": required, "reviewer_approval": approval, "upload_ok": not block,
            "public_ok": not block and not public, "blockers": block, "public_blockers": public}


# ------------------------------------------------------------------ combined
def evaluate(manifest: dict) -> dict:
    rel = manifest.get("release") or {}
    md = manifest.get("metadata") or {}
    q = quality(manifest["artifact"], rel.get("quality_report"))
    d = disclosure(manifest["platform"], rel.get("provenance"), rel.get("disclosure_decision"))
    lang = language(rel.get("language"), md.get("language"))
    parts = {"quality": q, "disclosure": d, "language": lang}
    blockers = [f"{k}: {b}" for k, v in parts.items() for b in v["blockers"]]
    public = [f"{k}: {b}" for k, v in parts.items() for b in v["public_blockers"]]
    return {"upload_ok": not blockers, "public_ok": not blockers and not public, "blockers": blockers, "public_blockers": public,
            "warnings": q["warnings"], **parts}
