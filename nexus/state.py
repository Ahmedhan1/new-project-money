"""NEXUS Project Memory & Recovery Engine.

The project remembers its own state in files that live in Git, so development never depends on a chat
session: NEXUS_STATE.json (machine-readable), NEXUS_HANDOFF.md (for the next agent/human, with an
auto-generated block), and registry/tasks.yaml (the development task registry).

`checkpoint()` refreshes those files, refuses to commit secrets or large/binary files, commits, and
pushes without ever forcing. If the push fails the checkpoint stays local and is retried next time.
"""
from __future__ import annotations

import json
import re
import subprocess
import time
from pathlib import Path

import yaml

from . import config

ROOT = config.ROOT
STATE_FILE = ROOT / "NEXUS_STATE.json"
HANDOFF_FILE = ROOT / "NEXUS_HANDOFF.md"
TASKS_FILE = config.REGISTRY_DIR / "tasks.yaml"
SCHEMA_VERSION = 1
STATUSES = ["planned", "in_progress", "implemented", "tested", "verified", "blocked", "deferred", "rejected"]
OPEN = ("planned", "in_progress", "implemented", "tested")  # not yet verified = still work to do
AUTO_BEGIN, AUTO_END = "<!-- AUTO:STATE (generated by `nexus checkpoint` - do not edit by hand) -->", "<!-- /AUTO:STATE -->"

MAX_FILE_BYTES = 2_000_000
BLOCKED_SUFFIXES = {".mp4", ".mov", ".mkv", ".avi", ".webm", ".wav", ".mp3", ".flac", ".m4a", ".gguf", ".onnx", ".safetensors", ".bin",
                    ".pt", ".pth", ".ckpt", ".db", ".sqlite", ".zip", ".7z", ".tar", ".gz", ".blend", ".exe", ".dll", ".env", ".pem", ".key"}
BLOCKED_NAMES = {".env", "rclone.conf", "storage.json", "settings.json", "credentials.json", "token.json", "id_rsa", "id_ed25519"}
SECRET_PATTERNS = [
    ("private key", re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH |DSA |PGP )?PRIVATE KEY")),
    ("GitHub token", re.compile(r"\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{30,}\b|\bgithub_pat_[A-Za-z0-9_]{40,}\b")),
    ("AWS access key", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("Hugging Face token", re.compile(r"\bhf_[A-Za-z0-9]{30,}\b")),
    ("Google API key", re.compile(r"\bAIza[0-9A-Za-z_\-]{35}\b")),
    ("Slack token", re.compile(r"\bxox[abprs]-[A-Za-z0-9\-]{10,}\b")),
    ("API key (sk-...)", re.compile(r"\bsk-[A-Za-z0-9_\-]{32,}\b")),
    ("hard-coded credential", re.compile(r"""(?i)\b(?:password|passwd|secret|api_?key|access_?token|auth_?token)\b\s*[:=]\s*["'][^"'\s${}<>]{12,}["']""")),
]


# ----------------------------------------------------------------- git helpers
def git(*args: str, check: bool = True, timeout: int = 120) -> str:
    r = subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True, timeout=timeout)
    if check and r.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {r.stderr.strip() or r.stdout.strip()}")
    return r.stdout.strip()


def git_info() -> dict:
    try:
        branch = git("rev-parse", "--abbrev-ref", "HEAD")
        head = git("rev-parse", "--short", "HEAD")
        subject = git("log", "-1", "--format=%s")
        dirty = [l for l in git("status", "--porcelain").splitlines() if l]
        upstream = git("rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{u}", check=False)
        ahead = int(git("rev-list", "--count", "@{u}..HEAD", check=False) or 0) if upstream else None
        return {"branch": branch, "commit": head, "subject": subject, "dirty_files": len(dirty), "upstream": upstream or None, "unpushed_commits": ahead}
    except (RuntimeError, OSError, subprocess.TimeoutExpired) as e:
        return {"branch": None, "commit": None, "subject": None, "dirty_files": None, "upstream": None, "unpushed_commits": None, "error": str(e)}


# ----------------------------------------------------------------- task registry
def load_tasks() -> list[dict]:
    return yaml.safe_load(TASKS_FILE.read_text(encoding="utf-8"))["tasks"]


def validate_tasks(tasks: list[dict]) -> list[str]:
    errs, ids = [], set()
    for t in tasks:
        for k in ("id", "priority", "title", "status", "acceptance", "next"):
            if k not in t:
                errs.append(f"{t.get('id', '?')}: missing '{k}'")
        if t.get("status") not in STATUSES:
            errs.append(f"{t.get('id')}: bad status {t.get('status')!r}")
        if t.get("status") == "verified" and not t.get("evidence"):
            errs.append(f"{t.get('id')}: 'verified' requires evidence")
        if t.get("id") in ids:
            errs.append(f"duplicate task id {t.get('id')}")
        ids.add(t.get("id"))
    for t in tasks:
        errs += [f"{t['id']}: unknown dependency {d}" for d in t.get("deps", []) if d not in ids]
    return errs


def next_tasks(tasks: list[dict] | None = None, n: int = 5) -> list[dict]:
    """Highest-priority tasks that are still open and whose dependencies are no longer open."""
    tasks = tasks if tasks is not None else load_tasks()
    by = {t["id"]: t for t in tasks}
    ready = [t for t in tasks if t["status"] in OPEN and all(by[d]["status"] not in ("planned", "in_progress", "blocked") for d in t.get("deps", []))]
    order = {s: i for i, s in enumerate(["in_progress", "implemented", "tested", "planned"])}
    return sorted(ready, key=lambda t: (t["priority"], order[t["status"]], t["id"]))[:n]


# ----------------------------------------------------------------- state file
def validate_state(s: dict) -> list[str]:
    need = {"schema_version": int, "project": str, "version": str, "phase": str, "updated": str, "git": dict, "current_task": (dict, type(None)),
            "next_tasks": list, "tasks": dict, "tests": dict, "jobs": dict, "blockers": list, "backup": dict, "environment": dict}
    errs = [f"missing key '{k}'" for k in need if k not in s]
    errs += [f"'{k}' has wrong type" for k, t in need.items() if k in s and not isinstance(s[k], t)]
    if s.get("schema_version") != SCHEMA_VERSION:
        errs.append(f"schema_version must be {SCHEMA_VERSION}")
    return errs


def _read_json(p: Path) -> dict | None:
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def _runtime() -> dict:
    """What only this machine knows (jobs, backups, models). Empty on a fresh clone - that is fine."""
    out = {"jobs": {"counts": {}, "active": []}, "backup": {"last": None, "restore_drill": None}, "models": []}
    if not config.DB_PATH.exists():
        return out
    try:
        from . import jobs
        out["jobs"] = jobs.summary()
    except Exception as e:
        out["jobs"] = {"counts": {}, "active": [], "error": str(e)}
    lb = _read_json(config.HOME / "last_backup.json")
    if lb:
        out["backup"]["last"] = {"ts": lb["ts"], "ok": lb["ok"], "copies": lb["copies"], "warning": lb.get("warning"),
                                 "destinations": [{"name": r["destination"], "ok": r["ok"], "snapshot": r.get("snapshot")} for r in lb["results"]]}
    rd = _read_json(config.HOME / "last_restore_drill.json")
    if rd:
        out["backup"]["restore_drill"] = {"ts": rd["ts"], "ok": rd["ok"]}
    inst = _read_json(config.MODELS / "installed.json")
    out["models"] = sorted(inst) if inst else []
    return out


def build_state(phase: str | None = None) -> dict:
    prev = _read_json(STATE_FILE) or {}
    tasks = load_tasks()
    nxt = next_tasks(tasks)
    counts: dict[str, int] = {}
    for t in tasks:
        counts[t["status"]] = counts.get(t["status"], 0) + 1
    rt = _runtime()
    tests = prev.get("tests", {})
    fast = _read_json(ROOT / "docs" / "results" / "fast_tests.json")
    if fast:
        tests = {**tests, "fast": fast}
    # The latest pinned three-account integration result (docs/results/integration/*.json) is a different tree from
    # this branch, so it is reported beside the branch's own suite, with its exact input SHAs.
    integ = sorted((ROOT / "docs" / "results" / "integration").glob("*.json"), key=lambda p: p.stat().st_mtime)
    ir = _read_json(integ[-1]) if integ else None
    if ir and isinstance(ir.get("results", {}).get("fast_suite"), dict):
        fs, ins = ir["results"]["fast_suite"], ir.get("inputs", {})
        shas = " / ".join(f"A{k[-1]} {v.get('sha', '')[:7]}" for k, v in ins.items())
        tests = {**tests, "integration": {"summary": f"{fs['passed']} passed, {fs['failed']} failed, {fs['skipped']} skipped "
                                          f"at {shas} (local {ir.get('environment', {}).get('os', '')}; "
                                          f"not run: {', '.join(ir.get('not_run', [])) or 'nothing'}) - {integ[-1].relative_to(ROOT).as_posix()}"}}
    cur = next((t for t in tasks if t["status"] == "in_progress"), nxt[0] if nxt else None)
    return {
        "schema_version": SCHEMA_VERSION,
        "project": "NEXUS VIDEO AI",
        "version": config.VERSION,
        "phase": phase or prev.get("phase", "hardening"),
        "updated": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        # `commit` is the commit this state was written on top of; the checkpoint commit itself is its child.
        "git": git_info(),
        "current_task": cur and {k: cur[k] for k in ("id", "title", "status", "next")},
        "next_tasks": [{"id": t["id"], "priority": t["priority"], "title": t["title"], "status": t["status"], "next": t["next"]} for t in nxt],
        "tasks": {"total": len(tasks), "by_status": counts, "registry": "nexus/registry/tasks.yaml"},
        "tests": tests,
        "jobs": rt["jobs"],
        "blockers": [{"id": t["id"], "title": t["title"], "why": t.get("blocked_by", t["next"])} for t in tasks if t["status"] == "blocked"],
        "backup": rt["backup"],
        "environment": {"models_installed": rt["models"] or prev.get("environment", {}).get("models_installed", []),
                        "data_home": "NEXUS_HOME (default: ./.nexus, never committed)"},
    }


def write_state(phase: str | None = None) -> dict:
    s = build_state(phase)
    errs = validate_state(s) + validate_tasks(load_tasks())
    if errs:
        raise ValueError("state/tasks invalid: " + "; ".join(errs))
    STATE_FILE.write_text(json.dumps(s, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    update_handoff(s)
    return s


def auto_block(s: dict) -> str:
    g, t = s["git"], s["tasks"]["by_status"]
    lines = [AUTO_BEGIN,
             f"- **Updated:** {s['updated']} · **version** {s['version']} · **phase** {s['phase']}",
             f"- **Branch:** `{g['branch']}` · **built on commit** `{g['commit']}` ({g['subject']})",
             "- **Tasks:** " + ", ".join(f"{t[k]} {k}" for k in STATUSES if k in t) + " (`python -m nexus tasks`)",
             "- **Tests:** " + (", ".join(f"{k}: {v.get('summary', v) if isinstance(v, dict) else v}" for k, v in s["tests"].items()) or "none recorded"),
             "- **Next tasks (in order):**"]
    lines += [f"  {i}. `{x['id']}` [{x['status']}] {x['title']} — {x['next']}" for i, x in enumerate(s["next_tasks"], 1)]
    if s["blockers"]:
        lines.append("- **Blocked:** " + "; ".join(f"`{b['id']}` {b['why']}" for b in s["blockers"]))
    lines.append(AUTO_END)
    return "\n".join(lines)


def update_handoff(s: dict) -> None:
    if not HANDOFF_FILE.exists():
        return
    text = HANDOFF_FILE.read_text(encoding="utf-8")
    block = auto_block(s)
    if AUTO_BEGIN in text and AUTO_END in text:
        text = text[: text.index(AUTO_BEGIN)] + block + text[text.index(AUTO_END) + len(AUTO_END):]
    else:
        text = text.rstrip() + "\n\n## Current state (auto)\n" + block + "\n"
    HANDOFF_FILE.write_text(text, encoding="utf-8")


# ----------------------------------------------------------------- safety scan
def scan_paths(paths: list[str]) -> list[str]:
    """Reasons why these files must not be committed (secrets, media, weights, databases, oversized files)."""
    problems = []
    for rel in paths:
        p = ROOT / rel
        if not p.is_file():
            continue  # deletion
        if p.name in BLOCKED_NAMES or p.suffix.lower() in BLOCKED_SUFFIXES:
            problems.append(f"{rel}: file type must not be committed (media/model/database/credential)")
            continue
        size = p.stat().st_size
        if size > MAX_FILE_BYTES:
            problems.append(f"{rel}: {size / 1e6:.1f} MB is too large for Git (limit {MAX_FILE_BYTES / 1e6:.0f} MB) - keep it in storage")
            continue
        try:
            text = p.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue  # small binary such as a PNG evidence frame
        for name, rx in SECRET_PATTERNS:
            m = rx.search(text)
            if m and not (rel.endswith("state.py") or "test_" in rel):
                problems.append(f"{rel}: looks like a {name} (line {text[: m.start()].count(chr(10)) + 1})")
    return problems


def changed_paths() -> list[str]:
    out = git("status", "--porcelain", "-z", "--untracked-files=all")
    paths, parts, i = [], out.split("\0"), 0
    while i < len(parts):
        e = parts[i]
        if len(e) > 3:
            paths.append(e[3:])
            if e[0] in "RC":
                i += 1  # skip the rename source
        i += 1
    return paths


# ----------------------------------------------------------------- checkpoint
def push(retries: int = 4) -> dict:
    branch = git("rev-parse", "--abbrev-ref", "HEAD")
    if not git("remote", check=False):
        return {"pushed": False, "reason": "no git remote configured"}
    err = ""
    for i in range(retries + 1):
        r = subprocess.run(["git", "-C", str(ROOT), "push", "-u", "origin", branch], capture_output=True, text=True, timeout=300)
        if r.returncode == 0:
            return {"pushed": True, "branch": branch}
        full = (r.stderr or r.stdout).strip()
        err = full[-300:]
        if any(k in full for k in ("rejected", "non-fast-forward", "fetch first")):  # someone else pushed: never force, never overwrite
            return {"pushed": False, "reason": "remote has commits this checkout does not have - run `git pull --rebase` and checkpoint again (NEXUS never force-pushes)",
                    "detail": err}
        if i < retries:
            time.sleep(2 ** (i + 1))
    return {"pushed": False, "reason": "network/remote unavailable - checkpoint is committed locally and will be pushed by the next checkpoint", "detail": err}


def checkpoint(message: str | None = None, do_push: bool = True, phase: str | None = None) -> dict:
    """Save project state, commit safe files, push. Never force-pushes, never commits secrets/media."""
    s = write_state(phase)
    paths = changed_paths()
    problems = scan_paths(paths)
    if problems:
        return {"ok": False, "committed": False, "pushed": False, "blocked": problems,
                "fix": "remove the secret / add the file to .gitignore, then run the checkpoint again. Nothing was committed."}
    out = {"ok": True, "committed": False, "pushed": False, "files": len(paths), "blocked": []}
    if paths:
        git("add", "-A")
        cur = s["current_task"]
        msg = message or f"Checkpoint: {cur['id']} {cur['title']}" if cur else message or "Checkpoint"
        git("commit", "-m", msg)
        out["committed"] = True
    out["commit"] = git("rev-parse", "--short", "HEAD")
    if do_push:
        p = push()
        out.update(pushed=p["pushed"], push=p)
    return out


def status() -> dict:
    s = build_state()
    return {"state": s, "state_file_valid": not validate_state(_read_json(STATE_FILE) or {}), "task_errors": validate_tasks(load_tasks())}


def resume_brief() -> str:
    """Everything a new session needs first, in one screen."""
    s = build_state()
    g = s["git"]
    lines = ["NEXUS VIDEO AI - resume brief", "=" * 31,
             f"branch {g['branch']} @ {g['commit']} ({g['subject']})",
             f"working tree: {g['dirty_files']} changed file(s); unpushed commits: {g['unpushed_commits']}",
             "", "Read first: NEXUS_HANDOFF.md, NEXUS_STATE.json", "", "Next tasks:"]
    lines += [f"  {i}. {t['id']} [{t['status']}] {t['title']}\n     -> {t['next']}" for i, t in enumerate(s["next_tasks"], 1)]
    act = s["jobs"].get("active", [])
    lines += ["", f"Production jobs needing attention: {len(act)}"]
    lines += [f"  {j['id']} {j['kind']} {j['status']} stage={j['stage']} {j.get('recovery') or ''}" for j in act]
    b = s["backup"]["last"]
    lines += ["", "Last backup: " + (f"{time.strftime('%Y-%m-%d %H:%M', time.localtime(b['ts']))} ok={b['ok']} copies={b['copies']}" if b else "never on this machine")]
    return "\n".join(lines)
