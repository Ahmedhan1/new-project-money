"""Regenerate docs/EDITING_ASSETS_CATALOG.md and docs/ASSET_LICENSES.md from the asset manifest (never edit them by hand).

    python scripts/maintenance/gen_asset_docs.py
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from nexus import assetlib  # noqa: E402


def main() -> int:
    cat = assetlib._entries()
    by = Counter(e["category"] for e in cat)
    lines = ["# Editing assets catalog", "", "Generated from `nexus/registry/asset_library.yaml` + `nexus/fx/transitions.py` by",
             "`scripts/maintenance/gen_asset_docs.py`. Do not edit by hand.", "",
             f"**{len(cat)} assets**: " + ", ".join(f"{k} {v}" for k, v in sorted(by.items())) + ".", "",
             "Kinds: **builtin** = a renderer feature (nothing to download); **generated** = made locally on install (own work, CC0);",
             "**download** = pinned URL + SHA-256, fetched on demand; **pack** = pinned archive, selected members extracted.", ""]
    for c in sorted(by):
        lines += [f"## {c} ({by[c]})", "", "| ID | Name | Kind | Group | Description | Parameters |", "|---|---|---|---|---|---|"]
        for e in sorted((x for x in cat if x["category"] == c), key=lambda x: x["id"]):
            ap = e.get("apply") or {}
            params = ap.get("effect") or ap.get("keyframes") or ap.get("captions") or e.get("params") or ({"duration": ap["duration"]} if "duration" in ap else "")
            if "effect" in ap:
                from nexus.fx import effects
                lp = effects.LOOK_PARAMS.get(ap["effect"]["type"])
                if lp:
                    params = "; ".join(f"{k}: {v}" for k, v in lp.items())
            lines.append(f"| `{e['id']}` | {e['name']} | {e['kind']} | {e.get('group', '')} | {e.get('description', '').replace('|', '/')} | "
                         f"{str(params).replace('|', '/')} |")
        lines.append("")
    (ROOT / "docs" / "EDITING_ASSETS_CATALOG.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    lic = Counter(e.get("license") for e in cat)
    out = ["# Asset licences", "", "Generated by `scripts/maintenance/gen_asset_docs.py` from the manifest. Every asset is checked by",
           "`assetlib.license_check` before install (allowed licence, commercial use confirmed, author, source and attribution",
           "recorded; downloads need a pinned URL + SHA-256, and OFL fonts their licence text, which is downloaded and kept next to",
           "the font). `tests/fast/test_a2_assetlib.py::test_manifest_is_valid_and_every_asset_has_licence_metadata` fails otherwise.", "",
           "## Policy", "", f"- Allowed: {', '.join(assetlib.policy()['allowed_licenses'])}",
           f"- Attribution text required: {', '.join(assetlib.policy()['attribution_required'])}",
           f"- Licence text must travel with the file: {', '.join(assetlib.policy()['bundle_license_text'])}",
           "- `NEXUS-AGPL-3.0` = renderer features that are part of NEXUS's own code (no separate file).",
           "- Generated assets (CC0-1.0) are NEXUS's own work, made on your machine by `nexus/assetlib/generators.py`.", "",
           "## Counts by licence", "", "| Licence | Assets |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in sorted(lic.items())]
    out += ["", "## Third-party files (downloaded on demand)", "", "| ID | Author | Licence | Source | SHA-256 (pinned) | Attribution |", "|---|---|---|---|---|---|"]
    for e in cat:
        if e["kind"] in ("download", "pack"):
            out.append(f"| `{e['id']}` | {e['author']} | {e['license']} | {e['source_url']} | `{e['sha256']}` | {e['attribution']} |")
    out += ["", "## Considered and not installed", "", "| Resource | Licence | Why |", "|---|---|---|"]
    out += [f"| {o['name']} | {o['license']} | {o['why']} |" for o in assetlib.optional_future()]
    out += ["", "## Verification result", "", f"{sum(assetlib.license_check(e)[0] for e in cat)}/{len(cat)} assets pass the licence check."]
    (ROOT / "docs" / "ASSET_LICENSES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(len(cat), "assets")
    return 0


if __name__ == "__main__":
    sys.exit(main())
