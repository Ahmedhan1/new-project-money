"""Release gate: what must be true before a PublishingManifest may be uploaded (privately) or made public.

Three independent checks, all recorded in the manifest (`release_check`) and its history:

1. Quality (Account 2's QualityReport, nexus.QualityReport/1; producer nexus/qa.py approve()):
   - the final output exists locally and matches its sha256 when one is given;
   - a QualityReport is attached, is valid, and is for this output;
   - status == PASSED_AUTOMATED_CHECKS (BLOCKED and NEEDS_FIXES block every upload; an unknown status blocks too);
   - no failed check of severity "critical" in any stage (even if the status disagrees);
   - public/unlisted additionally needs human_approval starting with "APPROVED" (A2 writes "PENDING ..." by default).
   No report = no upload. Automated checks never stand in for the human review.

2. AI-content disclosure (provenance -> categories -> the platform's field). See DISCLOSURE_CATEGORIES and PLATFORMS.
   Fields read on the platforms' first-party pages on 2026-11-13 (sources in PLATFORMS). Content is never marked
   non-AI unless no AI provenance exists AND the owner attested it; unknown provenance is disclosed as AI on any upload
   and blocks public publishing until the owner decides.

3. Language readiness per output (language, dialect, translation QA, terminology, OCR/glyphs, voice licence and
   consent, native review). A localized output whose language needs native review stays draft/private until every
   submitted line is approved by a reviewer for exactly that variety: an ar-EG review never clears ar-Gulf text.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

PASSED = "PASSED_AUTOMATED_CHECKS"
QR_STATUSES = {"BLOCKED", "NEEDS_FIXES", PASSED}           # nexus/qa.py approve() (Account 2)
QR_REQUIRED = {"output": str, "status": str, "stages": list, "human_approval": str}

# ------------------------------------------------------------------ disclosure model
