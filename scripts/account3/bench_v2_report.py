"""Write docs/ACCOUNT3_MODEL_BENCHMARKS.md, the routing table and measured model profiles from models_bench_v2.json.

    python scripts/account3/bench_v2_report.py [--profiles]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
CAPS = ["json", "reasoning", "summarization", "translation", "dialect", "writing", "long_context", "grounding", "instruction", "strategy"]
PROFILE_MODELS = ["deepseek-r1-0528-qwen3-8b", "ministral-3-14b", "glm-4.7-flash", "qwen3.5-4b", "qwen3.5-9b", "nemotron-nano-9b-v2",
                  "qwen3.6-35b-a3b", "qwen3.8-27b"]


def main() -> None:
    from nexus.intelligence.model_router import bench_v2 as b
    p = ROOT / "docs/results/account3/models_bench_v2.json"
    d = json.loads(p.read_text(encoding="utf-8"))
    d["routing"] = b.routing(d["models"])
    d["validity"] = {k: b.valid_run(v)[1] for k, v in d["models"].items()}
    p.write_text(json.dumps(d, indent=1, ensure_ascii=False), encoding="utf-8")

    rows = []
    for k, m in d["models"].items():
        spec = b.MODELS.get(k, {})
        vram = (m.get("vram") or "—").replace("\n", " + ")
        ok, why = b.valid_run(m)
        head = f"| {k} | {spec.get('params_b')} | {spec.get('licence')} |"
        if not ok:
            rows.append(head + " — | " + " | ".join("—" for _ in CAPS) + f" | — | — | {vram} | **invalid**: {why} |")
            continue
        rows.append(head + f" **{m['overall']}** | " + " | ".join(str(m["capabilities"].get(c, "—")) for c in CAPS)
                    + f" | {m['mean_latency_s']} | {m['median_tokens_per_s']} | {vram} | {why} |")
    rt = []
    for t, x in d["routing"].items():
        nxt = ", ".join(f"{r['model']} {r['score']}" for r in x["ranking"][1:3])
        review = "**required**" if x["requires_human_review"] else ("critical" if x["critical"] else "")
        rt.append(f"| {t} | {x['best']} | {x['score']} | {x['bar']} | {'yes' if x['meets_bar'] else 'no'} | {review} | {nxt} |")
    tmpl = (ROOT / "scripts/account3/bench_v2_report.md.tmpl").read_text(encoding="utf-8")
    doc = (tmpl.replace("{ITEMS}", str(d["items"])).replace("{CAPS}", " | ".join(CAPS)).replace("{CAPSEP}", "---|" * len(CAPS))
           .replace("{ROWS}", "\n".join(rows)).replace("{ROUTING}", "\n".join(rt)))
    (ROOT / "docs/ACCOUNT3_MODEL_BENCHMARKS.md").write_text(doc, encoding="utf-8")

    if "--profiles" in sys.argv:
        prov = ROOT / "nexus/intelligence/capability_registry/providers.yaml"
        text = prov.read_text(encoding="utf-8")
        marker = "  # ---- measured on Kaggle (bench_v2)"
        text = text.split("\n" + marker)[0].rstrip("\n") + "\n"
        out = [marker + " - batch-only until an owner GPU serves them; regenerated by scripts/account3/bench_v2_report.py"]
        for k in PROFILE_MODELS:
            m = d["models"].get(k)
            if not m or not b.valid_run(m)[0]:
                continue
            s, c = b.MODELS[k], m["capabilities"]
            q = {x: round(10 * c[y]) for x, y in (("reasoning", "reasoning"), ("writing", "writing"), ("json", "json"),
                                                   ("translation", "translation"), ("arabic", "dialect"), ("summarization", "summarization"))}
            lat = m.get("mean_latency_s") or 0
            out.append(f"  {k}-q4km:\n    family: {k.split('-')[0]}\n    weights: \"{s['pull']}\"\n    licence: \"{s['licence']}\"\n"
                       f"    commercial_use: \"yes\"\n    context: 8192\n    availability: batch_only\n"
                       f"    quality: {{{', '.join(f'{a}: {v}' for a, v in q.items())}, source: \"bench_v2 n={len(m['rows'])} (Kaggle T4x2, Q4_K_M)\"}}\n"
                       f"    speed: {'slow' if lat > 10 else 'medium' if lat > 3 else 'fast'}")
        prov.write_text(text + "\n".join(out) + "\n", encoding="utf-8")
    print("ok")


if __name__ == "__main__":
    main()
