"""Scene visual plan + the QA stages that enforce it (used by nexus/create.py).

Every scene gets an intentional visual: a licensed photo that passed the visual-context gate, or an explanatory fact
graphic for scenes that state a figure, or - only when neither exists - a title card that is FLAGGED and blocks
approval when it is more than a quarter of the scenes (unless the owner explicitly approved the fallback).
Found on a real render (Account 3 Demo 4): 2 of 4 scenes silently became title cards."""
from __future__ import annotations

import re
from pathlib import Path

from ... import qa
from . import typography, visual_context

MAX_FALLBACK_SHARE = 0.25


def context_for(script: dict, scene: dict) -> dict:
    ctx = visual_context.scene_context(script.get("topic", ""), scene.get("narration", ""), scene.get("visual_query", ""))
    ctx["subject"] = scene.get("visual_query") or script.get("topic", "")
    return ctx


def validate_asset(candidate: dict, ctx: dict) -> dict:
    return visual_context.check(candidate, ctx)


FIGURE = re.compile(r"(\d[\d,.]*\s*(?:%|percent|per cent|km²|square kilometres|square kilometers|km|m|metres|meters|years|million|billion|kWh|MW|GW)?)", re.I)


def key_fact(narration: str) -> tuple[str, str] | None:
    """The scene's most specific figure and a short label from the same sentence (for a fact graphic)."""
    for sent in re.split(r"(?<=[.!?])\s+", narration or ""):
        nums = [m.group(1).strip() for m in FIGURE.finditer(sent) if len(re.sub(r"\D", "", m.group(1))) >= 2]
        if nums:
            fig = max(nums, key=len)
            label = re.sub(r"\s+", " ", sent.replace(fig, "").strip(" ,.;:-"))
            return fig, label[:70]
    return None


def alternative_visual(scene: dict, work: Path, i: int, size: tuple[int, int], lang: str, dur: float) -> dict | None:
    """A deliberate explanatory visual when no licensed image fits: an animated fact graphic built from the scene's own
    sourced figure. Returns None when the scene states no figure (then a flagged title card is the honest result)."""
    kf = key_fact(scene.get("narration", ""))
    if not kf:
        return None
    from ...animation import mograph
    fig, label = kf
    out = Path(work) / f"fact{i:02d}.mp4"
    out.parent.mkdir(parents=True, exist_ok=True)
    mograph.kinetic_text(out, [fig, label], duration=max(3.0, dur), size=size, lang=lang)
    return {"path": str(out), "kind": "fact_graphic", "reason": f"no licensed image passed the context gate; scene states '{fig}'",
            "provenance": {"license": "generated by NEXUS (original)", "source": "fact graphic (motion graphics)", "figure": fig}}


def visual_stage(plan: list[dict], approved_fallback: bool = False) -> dict:
    checks = []
    n = len(plan)
    cards = [p for p in plan if p.get("kind") == "title_card_fallback"]
    share = len(cards) / n if n else 0.0
    checks.append(qa._c("scene visual plan", share <= MAX_FALLBACK_SHARE or approved_fallback,
                        f"{n - len(cards)}/{n} scenes have an intentional visual; title-card fallback in scenes "
                        f"{[p['scene'] + 1 for p in cards] or 'none'}" + (" (owner approved the fallback)" if approved_fallback and cards else ""),
                        "major", fix="find-visual"))
    rejected = [(p["scene"] + 1, r["title"], [f["check"] for f in r["findings"]]) for p in plan for r in p.get("rejected", [])]
    checks.append(qa._c("visual context gate", True, f"{len(rejected)} candidate image(s) refused before download: {rejected[:6]}" if rejected
                        else "no candidate needed refusing", "info"))
    kinds = [p.get("kind") for p in plan]
    checks.append(qa._c("visual variety", len(set(kinds)) >= min(2, n) or n < 3, f"visual kinds: {kinds}", "minor"))
    return {"stage": "2b-visual-plan", "checks": checks, "passed": all(c["ok"] or c["severity"] in ("minor", "info") for c in checks),
            "plan": plan}


def _texts(tl: dict) -> list[str]:
    out = []
    for c in tl.get("clips", []):
        out += [t["text"] for t in c.get("text", []) if t.get("text")]
    return out


def typography_stage(tl: dict, lang: str = "en", ocr: bool = True) -> dict:
    """Every burned-in string must have real glyphs (hard check); titles/credits are also read back from a rendered frame."""
    checks = []
    for t in _texts(tl):
        r = typography.check_text(t, lang)
        if not r["ok"]:
            checks.append(qa._c("missing glyphs", False, f"'{t[:60]}': {r['finding']}", "critical", fix="font"))
    long_or_mixed = [t for t in _texts(tl) if len(t) > 40 or any(ord(ch) > 0x2FF for ch in t)]
    for t in long_or_mixed[:4] if ocr else []:
        r = typography.render_check(t[:120], lang)
        if r.get("recall") is not None:
            checks.append(qa._c("text read-back (OCR)", r["recall"] >= 0.6, f"recall {r['recall']} for '{t[:50]}' -> '{(r['ocr'] or '')[:50]}'",
                                "minor"))
    if not checks:
        checks.append(qa._c("missing glyphs", True, f"{len(_texts(tl))} on-screen string(s), every character has a glyph", "info"))
    return {"stage": "2c-typography", "checks": checks, "passed": all(c["ok"] or c["severity"] in ("minor", "info") for c in checks)}
