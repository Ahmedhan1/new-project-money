"""LIVE Kaggle evidence through the NEXUS dispatcher (uses real free Kaggle GPU minutes). Skipped unless NEXUS_LIVE=1.

    NEXUS_LIVE=1 NEXUS_HOME=<home with the vault> python -m pytest -q tests/live/test_kaggle_live.py -s
    NEXUS_HOME=<home> python tests/live/test_kaggle_live.py probe|transcode|resume     # same, as a script

Each scenario writes docs/results/account1/kaggle_<name>.json (no secrets; the Kaggle username is replaced by
"<owner>"). Keep usage small: probe ~1 run, transcode 1 run, resume 2 runs.
"""
from __future__ import annotations

import json
import os
import platform
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "results" / "account1"
pytestmark = pytest.mark.skipif(os.environ.get("NEXUS_LIVE") != "1", reason="live Kaggle test: set NEXUS_LIVE=1")


def _dispatcher():
    from nexus.cloud.compute import dispatcher as dsp
    from nexus.cloud.compute.kaggle import KaggleProvider
    from nexus.cloud.compute.local import LocalProvider
    d = dsp.Dispatcher({"kaggle": KaggleProvider(), "local": LocalProvider()}, poll_min=10, poll_max=30)
    dsp.set_dispatcher(d)
    return d


def _sanitize(obj, user: str):
    from nexus import vault
    s = vault.redact(json.dumps(obj, default=str))
    if user:
        s = s.replace(user, "<owner>")
    return json.loads(s)


def _evidence(name: str, d, row: dict, extra: dict) -> dict:
    from nexus.cloud import events
    from nexus.cloud.compute import dispatcher as dsp
    user = d.providers["kaggle"].username()
    res = json.loads(row["result"]) if row.get("result") else {}
    arts = dsp.job_artifacts(row["id"])
    verified = []
    for a in arts:
        p = dsp.artifact_path(a)
        verified.append({"name": a["name"], "size": a["size"], "sha256": a["sha256"], "local_sha256_recomputed": dsp._sha(p) if p else None,
                         "match": bool(p) and dsp._sha(p) == a["sha256"]})
    ev = {"scenario": name, "date": time.strftime("%Y-%m-%d %H:%M:%S %Z"), "host_platform": platform.platform(),
          "job_id": row["id"], "task": row["task"], "status": row["status"], "provider": row["provider"], "attempts": row["attempts"],
          "kernel": "<owner>/" + (row["remote_ref"] or "").split("/", 1)[-1], "error": row["error"],
          "attempt_history": res.get("attempts"), "final_result": res.get("final"), "postprocess": res.get("postprocess"),
          "artifacts_verified": verified, "checkpoints": dsp.checkpoints(row["id"]),
          "events": [{k: e[k] for k in ("type", "message", "at")} for e in reversed(events.events(job_id=row["id"], limit=200))],
          "quota": d.providers["kaggle"].quota().model_dump(), **extra}
    ev = _sanitize(ev, user)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"kaggle_{name}.json").write_text(json.dumps(ev, indent=1) + "\n", encoding="utf-8")
    return ev


def _clip(seconds: int = 10) -> Path:
    """Synthetic test clip (testsrc2 + sine): created here, so public-domain by construction."""
    p = Path(tempfile.mkdtemp(prefix="nexus_live_")) / "nexus_testclip.mp4"
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", f"testsrc2=size=640x360:rate=30:duration={seconds}",
                    "-f", "lavfi", "-i", f"sine=frequency=440:duration={seconds}", "-c:v", "libx264", "-preset", "veryfast", "-crf", "35",
                    "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest", str(p)], check=True)
    return p


def run_probe() -> dict:
    from nexus.contracts import ProductionJobManifest
    d = _dispatcher()
    t0 = time.time()
    row, _ = d.submit(ProductionJobManifest(task="probe", requires={"gpu": True, "providers": ["kaggle"]}, max_retries=0, max_runtime_s=900))
    row = d.run_until_done(row["id"], timeout=1500, interval=5)
    cap = d.providers["kaggle"].capability().model_dump()
    return _evidence("probe", d, row, {"end_to_end_s": round(time.time() - t0, 1), "measured_capability": cap})


def run_transcode() -> dict:
    from nexus.cloud.compute import dispatcher as dsp
    from nexus.contracts import ProductionJobManifest
    d = _dispatcher()
    clip = _clip(10)
    art = dsp.register_local_file(clip, "source", rights="owned", licence="synthetic test pattern generated by NEXUS (public domain)")
    t0 = time.time()
    row, _ = d.submit(ProductionJobManifest(task="ffmpeg_transcode", inputs=[art.artifact_id], params={"encoder": "auto", "scale": "1280:-2"},
                                            requires={"gpu": True, "providers": ["kaggle"]}, max_retries=0, max_runtime_s=900))
    row = d.run_until_done(row["id"], timeout=1500, interval=5)
    probe = None
    out = [a for a in dsp.job_artifacts(row["id"]) if a["name"].endswith(".mp4")]
    if out and shutil.which("ffprobe"):
        r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "stream=codec_name,width,height:format=duration", "-of", "json",
                            str(dsp.artifact_path(out[0]))], capture_output=True, text=True)
        probe = json.loads(r.stdout or "{}")
    return _evidence("transcode", d, row, {"end_to_end_s": round(time.time() - t0, 1),
                                          "input": {"name": art.name, "size": art.size, "sha256": art.sha256, "licence": "synthetic, public domain"},
                                          "local_ffprobe_of_output": probe})


def run_resume() -> dict:
    from nexus.cloud.compute import dispatcher as dsp
    from nexus.contracts import ProductionJobManifest
    d = _dispatcher()
    clip = _clip(10)
    art = dsp.register_local_file(clip, "source", rights="owned", licence="synthetic test pattern generated by NEXUS (public domain)")
    t0 = time.time()
    row, _ = d.submit(ProductionJobManifest(task="chunked_transcode", inputs=[art.artifact_id],
                                            params={"chunks": 4, "encoder": "auto", "simulate_loss_after": 2, "scale": "1280:-2"},
                                            requires={"gpu": True, "providers": ["kaggle"]}, max_retries=1, max_runtime_s=900))
    row = d.run_until_done(row["id"], timeout=2400, interval=5)
    return _evidence("resume", d, row, {"end_to_end_s": round(time.time() - t0, 1),
                                       "how_loss_was_simulated": "attempt 1 ran with params.simulate_loss_after=2: the worker stopped after "
                                       "chunk 2 and reported status 'lost'; the dispatcher stored its checkpoints and verified chunks, emitted "
                                       "worker.lost and re-pushed the job with the last JobCheckpoint embedded"})


def test_live_probe():
    ev = run_probe()
    assert ev["status"] == "succeeded" and all(a["match"] for a in ev["artifacts_verified"])


def test_live_transcode():
    ev = run_transcode()
    assert ev["status"] == "succeeded" and all(a["match"] for a in ev["artifacts_verified"])


def test_live_resume():
    ev = run_resume()
    assert ev["status"] == "succeeded"
    h = ev["attempt_history"]
    assert h[0]["outcome"] == "lost" and h[-1]["metrics"]["chunks_skipped"] == [0, 1]


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT))
    which = sys.argv[1] if len(sys.argv) > 1 else "probe"
    e = {"probe": run_probe, "transcode": run_transcode, "resume": run_resume}[which]()
    print(json.dumps({k: e[k] for k in ("status", "attempts", "error", "end_to_end_s")}, indent=1))
