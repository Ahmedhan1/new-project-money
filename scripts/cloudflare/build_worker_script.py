"""Generate cloudflare/src/worker_script.generated.js from nexus/cloud/worker_kit (the real NEXUS worker) and
cloudflare/studio/studio_kernel.py (the full-app studio session).

The Cloudflare control plane pushes exactly the same single-file worker to Kaggle that the Python dispatcher pushes;
this script freezes it into a JS module so the Worker needs no Python at runtime. Run after changing worker_kit:

    python scripts/cloudflare/build_worker_script.py          # write
    python scripts/cloudflare/build_worker_script.py --check  # exit 1 if the committed file is stale (used by tests)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from nexus.cloud import worker_kit  # noqa: E402

OUT = ROOT / "cloudflare" / "src" / "worker_script.generated.js"
STUDIO = ROOT / "cloudflare" / "studio" / "studio_kernel.py"


def render() -> str:
    script = worker_kit.build_script(None)
    return ("// GENERATED by scripts/cloudflare/build_worker_script.py from nexus/cloud/worker_kit - do not edit by hand.\n"
            f"export const WORKER_VERSION = {json.dumps(worker_kit.worker_version())};\n"
            f"export const WORKER_TASKS = {json.dumps(worker_kit.registered_worker_tasks())};\n"
            f"export const WORKER_SCRIPT = {json.dumps(script, ensure_ascii=True)};\n"
            f"export const STUDIO_SCRIPT = {json.dumps(STUDIO.read_text(encoding='utf-8'), ensure_ascii=True)};\n")


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python scripts/cloudflare/build_worker_script.py")
            return 1
        print("up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
