"""Test E - animated infographic, 2D explainer (Manim), 3D animation (Blender), motion graphics; composited into one timeline."""
import json
import time

from nexus import project, qa
from nexus.animation import engines, mograph
from nexus.media import ff
from nexus.speech import tts
from nexus.timeline import ops, subs


def test_e_animation(results):
    p = project.Project.create("Test E - animation reel", "animation")
    d = p.dir / "work"
    t = {}
    t0 = time.time()
    info = mograph.bar_chart(d / "chart.mp4", "Cost of electricity by source", [("Solar PV", 44), ("Onshore wind", 33), ("Gas", 76), ("Coal", 118), ("Nuclear", 182)],
                             unit=" $/MWh", source="illustrative demo data", duration=6)
    t["infographic_s"] = round(time.time() - t0, 1); t0 = time.time()
    kin = mograph.kinetic_text(d / "kinetic.mp4", ["Clean power", "is now the", "cheapest power"])
    t["kinetic_s"] = round(time.time() - t0, 1); t0 = time.time()
    tline = mograph.timeline_animation(d / "timeline.mp4", "A short history of solar", [("1839", "Photovoltaic effect discovered"),
                                       ("1954", "First practical silicon cell"), ("2000s", "Feed-in tariffs scale the market"), ("Today", "Cheapest new electricity")])
    t["timeline_s"] = round(time.time() - t0, 1); t0 = time.time()
    exp = engines.manim_explainer(d / "explainer.mp4", "How a solar cell works", [
        {"label": "Sunlight", "detail": "Photons hit the silicon"}, {"label": "Electrons", "detail": "Energy knocks electrons loose"},
        {"label": "Current", "detail": "The junction pushes them one way"}, {"label": "Power", "detail": "Wires carry the current to your home"}])
    t["manim_s"] = round(time.time() - t0, 1)
    b3d = engines.blender_title(d / "title3d.mp4", "NEXUS", seconds=2.0, size=(640, 360), samples=20)
    t["blender"] = b3d
    for f in (info, kin, tline, exp, b3d["path"]):
        pr = ff.probe(f)
        assert pr["video"] and pr["duration"] > 1.5 and not ff.decode_check(f), f
        p.data.setdefault("generated", {})[str(f)] = {"license": "generated by NEXUS (original)", "source": "animation studio"}
    p.save()
    # composite everything on one timeline with narration + music
    tl = project.new_timeline(1280, 720)
    tl["clips"] = [ops.video_clip(b3d["path"], 0, ff.duration(b3d["path"]), fit="contain", fade_in=0.3),
                   ops.video_clip(str(kin), 0, ff.duration(kin), transition="crossfade", transition_dur=0.4),
                   ops.video_clip(str(exp), 0, ff.duration(exp), transition="crossfade", transition_dur=0.4,
                                  text=[{"text": "2D explainer - Manim", "style": "callout", "start": 0.5, "end": 3.5}]),
                   ops.video_clip(str(info), 0, ff.duration(info), transition="crossfade", transition_dur=0.4),
                   ops.video_clip(str(tline), 0, ff.duration(tline), transition="crossfade", transition_dur=0.4, fade_out=0.6)]
    line = "Clean power is now the cheapest power. Here is how a solar cell turns light into electricity, and what it costs."
    v = tts.synthesize(line, p.dir / "audio" / "vo.wav", "en")
    tl["audio"] = [{"src": v["path"], "start": 2.2}]
    tl["subtitles"] = subs.cues_from_text(line, 2.2, 2.2 + v["duration"])
    from nexus.audio import music
    tl["music"] = {"src": str(music.music_bed(40, "inspiring", 3)), "volume": 0.5}
    p.save_timeline(tl, "animation reel")
    stats, report = qa.render_with_qa(p, tl, "animation_reel")
    assert report["status"] == "PASSED_AUTOMATED_CHECKS", report["known_issues"]
    for name, ts in (("3d", 1.0), ("kinetic", 4.2), ("manim", 12.0), ("chart", 22.0), ("timeline", 28.5)):
        ff.run(["-ss", ts, "-i", stats["output"], "-frames:v", "1", results / f"E_{name}.png"])
    (results / "E_animation.json").write_text(json.dumps({"timings": t, "reel": {"duration": stats["duration"], "status": report["status"],
                                                          "render_seconds": stats["elapsed"]}}, indent=1))
