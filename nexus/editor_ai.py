"""Editor brain for simple mode: WHAT to keep (story selection) and HOW it should look (finishing pass).

Selection - the edit must represent the whole video, never "the first N minutes":
  * talking video + local LLM: the model reads the numbered transcript (with times) and picks a story of the requested
    length: a hook that opens, the key points in order, a clean ending (the way an editor makes a summary cut).
  * otherwise: every shot/sentence gets a content score (speech density, motion, sharpness, faces, the analysis'
    "moments"), and the timeline is split into equal windows; each window contributes its best material, so the cut
    spans the beginning, middle and end. Ties never fall back to timeline order.
Finishing (on the editable timeline; the existing renderer does the work):
  * transitions only where the source really jumps (scene change), style-dependent; continuous speech gets none
  * jump cuts inside one shot are hidden with alternating framing (1.0 / 1.08 punch-in)
  * long shots get a slow Ken Burns push-in; a colour grade per style; a licence-clean music bed (CC0, generated by the
    asset library) ducked under speech; fades in/out.
"""
from __future__ import annotations

import math

STYLES = {  # transition names are ffmpeg xfade names (nexus/fx/transitions.py), grade names are fx.post.GRADES
    "auto": {"transitions": ["fade"], "tdur": 0.35, "grade": "cinematic", "music": "music.documentary_bed", "kenburns": 1.05},
    "documentary": {"transitions": ["fade", "fadeblack"], "tdur": 0.45, "grade": "documentary", "music": "music.documentary_bed",
                    "kenburns": 1.06},
    "explainer": {"transitions": ["smoothleft", "fade"], "tdur": 0.3, "grade": "vivid", "music": "music.inspiring_bed", "kenburns": 1.04},
    "podcast": {"transitions": ["fade"], "tdur": 0.25, "grade": "warm", "music": None, "kenburns": 1.03},
    "interview": {"transitions": ["fade"], "tdur": 0.35, "grade": "film_warm", "music": "music.calm_bed", "kenburns": 1.04},
    "vlog": {"transitions": ["slideleft", "zoomin", "smoothleft", "fade"], "tdur": 0.3, "grade": "golden_hour",
             "music": "music.upbeat_bed", "kenburns": 1.06},
    "social": {"transitions": ["zoomin", "slideleft", "smoothup", "fadewhite"], "tdur": 0.22, "grade": "vivid",
               "music": "music.upbeat_bed", "kenburns": 1.07},
}


# ---------------------------------------------------------------- scoring
def _segments(an: dict) -> list[dict]:
    return [s for s in ((an.get("transcript") or {}).get("segments") or []) if s.get("end", 0) > s.get("start", 0)]


def _moment_bonus(an: dict, a: float, b: float) -> float:
    bonus = 0.0
    for m in an.get("moments") or []:
        ms, me = float(m.get("start", 0)), float(m.get("end", 0))
        if me > a and ms < b:
            bonus = max(bonus, float(m.get("score", 0.5) or 0.5))
    hook = ((an.get("understanding") or {}).get("narrative") or {}).get("hook") or {}
    if isinstance(hook, dict) and hook.get("start") is not None and a <= float(hook["start"]) < b:
        bonus += 0.5
    return bonus


def _shot_scores(an: dict) -> list[dict]:
    dur = float(an["probe"]["duration"])
    shots = an.get("shots") or [{"start": a, "end": b} for a, b in (an.get("scenes") or [(0.0, dur)])]
    if not shots:
        shots = [{"start": 0.0, "end": dur}]
    mot = [float(s.get("motion") or 0) for s in shots]
    shp = [float(s.get("sharpness") or 0) for s in shots]
    mmax, smax = max(mot) or 1.0, max(shp) or 1.0
    out = []
    for s, m, h in zip(shots, mot, shp):
        a, b = float(s["start"]), float(s["end"])
        score = 0.35 * (m / mmax) + 0.2 * (h / smax) + 0.3 * float(s.get("speech_share") or 0) + 0.15 * min(1.0, float(s.get("faces") or 0))
        out.append({"in": a, "out": b, "score": score + _moment_bonus(an, a, b), "segs": []})
    return out


def _sentence_ranges(an: dict) -> list[dict]:
    """One range per transcript segment, scored by information density + the analysis' moments/hook."""
    segs = _segments(an)
    out = []
    for i, s in enumerate(segs):
        a, b = float(s["start"]), float(s["end"])
        words = len(str(s.get("text", "")).split())
        density = min(1.0, words / max(1.0, (b - a) * 3.0))
        out.append({"in": a, "out": b, "score": density + float(s.get("score", 0) or 0) + _moment_bonus(an, a, b), "segs": [i]})
    return out


# ---------------------------------------------------------------- selection
def stratified(ranges: list[dict], dur: float, target: float, piece: float | None = None) -> list[dict]:
    """Cover the whole timeline: split it into equal windows, take the best-scoring material of each window."""
    if not ranges:
        return []
    piece = piece or max(4.0, min(20.0, target / 12))
    k = max(1, min(len(ranges), int(math.ceil(target / piece))))
    win = dur / k
    chosen, used = [], 0.0
    for w in range(k):
        a, b = w * win, (w + 1) * win
        inside = [r for r in ranges if r["out"] > a and r["in"] < b]
        if not inside:
            continue
        budget = target / k
        for r in sorted(inside, key=lambda r: -r["score"]):
            if budget < 1.0:
                break
            ra, rb = max(r["in"], a), min(r["out"], b)
            if rb - ra < 0.8:
                continue
            take = min(rb - ra, budget)
            mid = (ra + rb) / 2  # take the centre of a long shot, not its first seconds
            s0 = max(ra, min(mid - take / 2, rb - take))
            chosen.append({**r, "in": round(s0, 3), "out": round(s0 + take, 3)})
            budget -= take
            used += take
    chosen.sort(key=lambda r: r["in"])
    # top up (rounding / empty windows) with the best remaining material, anywhere
    if used < target * 0.97:
        for r in sorted(ranges, key=lambda r: -r["score"]):
            if used >= target * 0.97:
                break
            if any(c["in"] < r["out"] and r["in"] < c["out"] for c in chosen):
                continue
            take = min(r["out"] - r["in"], target - used)
            if take >= 1.0:
                chosen.append({**r, "out": round(r["in"] + take, 3)})
                used += take
        chosen.sort(key=lambda r: r["in"])
    return chosen


def llm_story(an: dict, target: float, instructions: str = "", title: str = "") -> dict | None:
    """Ask the local LLM to pick the story. Returns {"keep": [segment indices], "title", "why"} or None."""
    segs = _segments(an)
    if len(segs) < 4:
        return None
    try:
        from . import llm
    except Exception:  # noqa: BLE001
        return None
    lines, budget = [], 22000  # characters of transcript the 8k-token context can hold with room for the answer
    step = max(1, int(math.ceil(sum(len(str(s.get("text", ""))) + 18 for s in segs) / budget)))
    for i, s in enumerate(segs):
        if i % step and step > 1:
            continue
        lines.append(f"{i} [{int(s['start']) // 60}:{int(s['start']) % 60:02d}] {str(s.get('text', '')).strip()[:160]}")
    total = sum(float(s["end"]) - float(s["start"]) for s in segs)
    prompt = (f"You are a senior film editor. Cut this {int(float(an['probe']['duration']) // 60)}-minute video down to about "
              f"{int(target)} seconds of speech (the transcript has about {int(total)} seconds).\n"
              "Rules: start with the strongest hook line; keep the main ideas in their original order; every kept line must make "
              "sense without the removed ones (keep the line before a reply when needed); end on a conclusive line; cover the whole "
              "video, not only its beginning; drop filler, repetition, greetings and tangents.\n"
              + (f"Owner's instructions: {instructions}\n" if instructions else "")
              + "Return JSON {\"keep\": [line numbers in order], \"title\": short title in the video's language, "
              "\"why\": one sentence}.\nTranscript (line number, time, text):\n" + "\n".join(lines))
    schema = {"type": "object", "properties": {"keep": {"type": "array", "items": {"type": "integer"}, "minItems": 3},
                                               "title": {"type": "string"}, "why": {"type": "string"}},
              "required": ["keep", "title", "why"]}
    try:
        out = llm.chat_json(prompt, max_tokens=1200, temperature=0.3, require="keep", schema=schema)
    except Exception:  # noqa: BLE001 - no local LLM: the caller uses the scored selection
        return None
    keep = sorted({int(i) for i in (out or {}).get("keep") or [] if isinstance(i, int) and 0 <= int(i) < len(segs)})
    if len(keep) < 3:
        return None
    return {"keep": keep, "title": str(out.get("title") or title)[:80], "why": str(out.get("why") or "")[:300]}


def _fit_sentences(an: dict, keep: list[int], target: float) -> list[dict]:
    """LLM-chosen lines -> ranges at the requested length: add the next-best lines or drop the weakest until it fits."""
    segs = _segments(an)
    scored = {r["segs"][0]: r for r in _sentence_ranges(an)}
    chosen = set(keep)

    def length() -> float:
        return sum(float(segs[i]["end"]) - float(segs[i]["start"]) for i in chosen)

    others = sorted((i for i in scored if i not in chosen), key=lambda i: -scored[i]["score"])
    while length() < target * 0.95 and others:
        chosen.add(others.pop(0))
    weakest = sorted(chosen, key=lambda i: scored[i]["score"])
    while length() > target * 1.05 and len(chosen) > 3 and weakest:
        i = weakest.pop(0)
        if i != min(keep):  # never drop the opening hook the editor chose
            chosen.discard(i)
    # join lines that are close in the source into one continuous piece (natural speech, fewer cuts)
    out: list[dict] = []
    for i in sorted(chosen):
        a, b = max(0.0, float(segs[i]["start"]) - 0.12), float(segs[i]["end"]) + 0.18
        if out and a - out[-1]["out"] <= 0.9:
            out[-1]["out"], out[-1]["segs"] = b, out[-1]["segs"] + [i]
        else:
            out.append({"in": a, "out": b, "score": scored[i]["score"], "segs": [i]})
    return out


def choose(an: dict, target: float, instructions: str = "", title: str = "", use_llm: bool = True) -> dict:
    """{"keep": ranges, "how": Arabic explanation, "title"}: the material for a cut of `target` seconds."""
    dur = float(an["probe"]["duration"])
    target = max(5.0, min(target, dur))
    if target >= dur * 0.97:
        return {"keep": [{"in": 0.0, "out": dur, "score": 1.0, "segs": list(range(len(_segments(an))))}],
                "how": "المدة اللي طلبتها قد الفيديو كله: سبته كامل", "title": title}
    if _segments(an) and use_llm:
        story = llm_story(an, target, instructions, title)
        if story:
            keep = _fit_sentences(an, story["keep"], target)
            return {"keep": keep, "title": story["title"] or title,
                    "how": f"الذكاء الاصطناعي قرا الكلام كله واختار القصة: {story['why']}".strip()}
    ranges = _sentence_ranges(an) if _segments(an) else _shot_scores(an)
    keep = stratified(ranges, dur, target)
    what = "أقوى الجمل" if _segments(an) else "أقوى اللقطات (حركة، وضوح، وشوش)"
    return {"keep": keep, "title": title, "how": f"اخترت {what} من أول الفيديو ووسطه وآخره بالتساوي (مش بس البداية)"}


# ---------------------------------------------------------------- finishing
def polish(tl: dict, style: str = "auto", speech: bool = True) -> dict:
    """Make a cut look edited: transitions at real scene jumps, jump-cut framing, Ken Burns, grade, music bed."""
    st = STYLES.get(style) or STYLES["auto"]
    clips = [c for c in tl.get("clips", []) if c.get("src")]
    prev = None
    flip = False
    tn = 0
    for c in tl.get("clips", []):
        if not c.get("src"):
            prev = None
            continue
        d = float(c["out"]) - float(c["in"])
        effects = [e for e in c.get("effects") or [] if e.get("type") not in ("zoom", "punch_in")]
        if prev is not None:
            gap = float(c["in"]) - float(prev["out"])
            same_shot = 0 <= gap < 4.0
            if same_shot:  # a cut inside one continuous shot: change the framing so it reads as a new angle
                flip = not flip
            elif d > 1.2 and float(prev["out"]) - float(prev["in"]) > 1.2:
                c["transition"] = "crossfade"
                c["xfade"] = st["transitions"][tn % len(st["transitions"])]
                c["transition_dur"] = min(st["tdur"], d / 4)
                tn += 1
                flip = False
        if flip:
            effects.append({"type": "zoom", "from": 1.08, "to": 1.08})
        elif d >= 6.0:  # slow push-in keeps long shots alive
            effects.append({"type": "zoom", "from": 1.0, "to": st["kenburns"]})
        c["effects"] = effects
        prev = c
    tl["grade"] = st["grade"]
    if clips:
        clips[0]["fade_in"] = max(float(clips[0].get("fade_in") or 0), 0.4)
        clips[-1]["fade_out"] = max(float(clips[-1].get("fade_out") or 0), 0.8)
    if st["music"]:
        try:
            from . import assetlib
            rec = assetlib.install(st["music"])
            src = (rec.get("files") or [rec.get("path")])[0]
            if src:
                tl["music"] = {"src": src, "volume": 0.16 if speech else 0.55, "duck": "keyframes" if speech else False,
                               "licence": rec.get("license") or "CC0-1.0", "asset": st["music"]}
        except Exception:  # noqa: BLE001 - no music bed is better than no video
            pass
    return tl
